#!/usr/bin/env node
// One-time generator: turns a FIGlet font into a 52-glyph big-text font file
// (A-Z then a-z) for src/components/text/bigText.ts.
//
// figlet is only needed here, not at runtime:
//   npm install --no-save figlet
//   node scripts/extract-big-font.mjs "Gothic" src/data/fonts/gothic.ts
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const [fontName, outPath] = process.argv.slice(2)
if (!fontName || !outPath) {
  console.error('usage: node scripts/extract-big-font.mjs <FontName> <out.ts>')
  process.exit(1)
}

// Import the module so the template literal is evaluated: reading the file as
// text would leave `\` doubled.
const { default: flfModule } = await import(
  `../node_modules/figlet/importable-fonts/${fontName}.js`
)
const flf = String(flfModule)
const lines = flf.split('\n')
const header = lines[0].split(/\s+/)
const height = Number(header[1])
const hardblank = header[0][5]

// Glyph rows are terminated with the font's end-mark ('@' by spec, '#' in some
// JavE-made fonts); the first run of `height` such lines begins the glyph data.
const endMark = lines.some((line) => /@+$/.test(line)) ? '@' : '#'
const isRow = (line) => line.includes(endMark) && new RegExp(`${endMark}+$`).test(line)
let start = -1
for (let i = 0; i < lines.length; i++) {
  if (lines.slice(i, i + height).every(isRow)) {
    start = i
    break
  }
}
// The lines before the glyph data carry the font's authorship; keep them in the
// generated file so the credit travels with the art.
const provenance = []
for (const line of lines.slice(1)) {
  if (!line.trim() || /^(Explanation|flf2|Usage|`|-+$)/i.test(line.trim())) break
  provenance.push(line.trim())
}

if (start < 0) {
  console.error(`font "${fontName}": no glyph rows found`)
  process.exit(1)
}
const data = lines.slice(start)
const glyphAt = (code) => {
  const index = code <= 0x7e ? code - 32 : code - 0x7e + 94
  return data.slice(index * height, index * height + height)
}

const cleanRow = (row) =>
  row
    .replace(new RegExp(`${endMark}+$`), '')
    .split(hardblank)
    .join(' ')
    .replace(/\s+$/, '')

const block = (code) => {
  const rows = glyphAt(code).map(cleanRow)
  if (rows.length !== height) return null
  const width = Math.max(...rows.map((row) => row.length))
  return rows.map((row) => row.padEnd(width, ' ')).join('\n')
}

const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'
const blocks = [...letters].map((char) => block(char.charCodeAt(0)))
if (blocks.some((entry) => !entry)) {
  console.error(`font "${fontName}" does not carry the full alphabet (height ${height})`)
  process.exit(1)
}
const varName = fontName
  .toLowerCase()
  .split(/[^a-z0-9]+/)
  .filter(Boolean)
  .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
  .join('')
const body = blocks.map((entry) => `    ${JSON.stringify(entry)}`).join(',\n')

// Keep the font's own authorship lines in the generated file, so the credit
// travels with the art.
const credit =
  provenance.length > 0
    ? [
        '//',
        ...provenance.map((line) => `// ${line}`),
        '//',
        '// Freely reusable big-letter ASCII art; the lines above are the font’s own',
        '// credit, kept as attribution.',
        '',
      ].join('\n')
    : ''

writeFileSync(
  fileURLToPath(new URL(`../${outPath}`, import.meta.url)),
  `// Generated by scripts/extract-big-font.mjs from FIGlet's "${fontName}" font.
// 52 glyph blocks: A-Z then a-z. Every row is padded to the glyph's own width.
${credit}import type { BigFont } from '@/components/text/bigText'

export const ${varName}: BigFont = {
  name: '${fontName}',
  rows: ${height},
  glyphs: [
${body},
  ],
}
`,
)
console.log(`${fontName}: ${blocks.length} glyphs, height ${height} -> ${outPath}`)
